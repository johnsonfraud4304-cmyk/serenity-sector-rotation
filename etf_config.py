def get_etfs_by_category():
    categories = {}
    for name, (code, full_name, category) in ETF_LIST.items():
        if category not in categories:
            categories[category] = []
        categories[category].append({
            'name': name,
            'code': code,
            'full_name': full_name,
            'color': SECTOR_COLORS.get(category, '#6b7280'),
        })
    return categories

